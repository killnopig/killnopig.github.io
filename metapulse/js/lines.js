  // ⑤ 搖擺走路：左右晃著往右走
  const sway = [];
  for (let k = 0; k < 2; k++) {
    for (let x = 0, j = 0; x + 8 <= P; x += 2, j++) sway.push(pixelLine(W, [[j % 2 ? PX.swayB : PX.swayA, x]]));
    sway.push(textFrame('吃飽散散步～'), textFrame('吃飽散散步～'), textFrame('吃飽散散步～'));
  }
