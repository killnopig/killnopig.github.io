function rng(seed) { // mulberry32
  let a = seed >>> 0;
  return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
function shuffled(n, seed) {
  const a = [...Array(n).keys()], r = rng(seed);
  for (let i = n - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}
/** 以斷食開始的「日期」當種子：同一次斷食順序固定，換一天就不一樣 */
export function daySeed(start) { const d = new Date(start); return d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate(); }

/** 第 k 句（k 從 0 開始）：k < 前半句數 × 後半句數 時保證不重複，而且相鄰兩句的前、後半句都不一樣 */
export function comboAt(heads, tails, k, seed, sep = '，') {
  const H = heads.length, T = tails.length, total = H * T;
  k = ((k % total) + total) % total;
  const hp = shuffled(H, seed), tp = shuffled(T, seed * 7 + 3);
  const r = k % H, q = Math.floor(k / H);
  return heads[hp[r]] + sep + tails[tp[(q + 2 * r) % T]];   // 2r：換行（r 從頭再來）時後半句也不會跟上一句一樣
}

/** 燃料那一行（不含階段名稱）：idx = 第幾階段，stageStartMs = 那個階段開始的時間 */
export function fuelText(idx, stageStartMs, now, fastStart) {
  const p = FUEL[Math.max(0, Math.min(FUEL.length - 1, idx))];
  const k = Math.floor(Math.max(0, now - stageStartMs) / STEP);
  return p.emoji + ' ' + comboAt(p.heads, p.tails, k, daySeed(fastStart) * 10 + idx);
}

/** 熱血雞湯：照已斷食幾小時分段 */
export function soupText(now, fastStart) {
  const hrs = Math.max(0, now - fastStart) / 3600000;
  let gi = 0; SOUP.forEach((g, i) => { if (hrs >= g.from) gi = i; });
  const g = SOUP[gi], k = Math.floor(Math.max(0, now - (fastStart + g.from * 3600000)) / STEP);
  return comboAt(g.heads, g.tails, k, daySeed(fastStart) * 10 + 5 + gi);
}

