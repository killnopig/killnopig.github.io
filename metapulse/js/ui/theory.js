const ALL = [...STEPS, ...GUARDS];
const chipOf = s => s.name || (s.id === 'core' ? '能量平衡' : s.verb + ' ' + s.lab);

function fill(sh, i) {
  const s = ALL[i], prev = (i - 1 + ALL.length) % ALL.length, next = (i + 1) % ALL.length;
  sh.querySelectorAll(':scope > :not(.grab)').forEach(x => x.remove());
  const body = h('div.th-body');
  /* 小標放進第一段同一行（段落開頭的才併，公式、清單維持在上面） */
  const sec = ([t, b]) => b.startsWith('<p>') ? '<div class="th-sec"><p><b class="th-h">' + t + '</b>' + b.slice(3) + '</div>' : '<div class="th-sec"><h3>' + t + '</h3>' + b + '</div>';
  body.innerHTML = '<p class="th-meme"><span class="th-kicker">' + s.kicker + '</span>' + (s.meme ? '「' + s.meme + '」' : '') + '</p><p class="th-lead">' + s.lead + '</p>'
    + s.secs.map(sec).join('')
    + '<div class="th-limit"><b class="th-h">限制</b>' + s.limit + '</div>';
  sh.append(h('div.sheet-h', h('b.one', s.title), h('button.link', { type: 'button', onclick: () => closeSheet() }, '關閉')), body,
    h('div.row.between.th-nav',
      h('button.ghost', { type: 'button', onclick: () => { fill(sh, prev); sh.scrollTop = 0; } }, '‹ ' + ALL[prev].title.split('：')[0]),
      h('button.ghost', { type: 'button', onclick: () => { fill(sh, next); sh.scrollTop = 0; } }, ALL[next].title.split('：')[0] + ' ›')));
}
const openStep = i => openSheet(sh => fill(sh, i));

